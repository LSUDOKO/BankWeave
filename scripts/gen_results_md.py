"""Write the README results section from eval/results/*.json (numbers never typed by hand)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = {p.stem: json.loads(p.read_text()) for p in (ROOT / "eval" / "results").glob("*.json")}


def pct(x):
    return "—" if x is None else f"{x * 100:.1f}%"


def src(e):
    return f"<sub>`eval/results/{e['experiment']}.json`, commit `{e['commit']}`, {e['dataset']}</sub>"


out = ["<!-- results:start (generated by scripts/gen_results_md.py; do not edit by hand) -->", ""]
if "E1_alert_triage" in R:
    e = R["E1_alert_triage"]
    p, r = e["params"], e["results"]
    out += ["### E1: alert triage (IBM HI-Small, 20-bank consortium)", "",
            f"{p['test_accounts']:,} alerted accounts from the later half of the period "
            f"({p['illicit_in_test']} illicit, base rate {pct(p['illicit_in_test'] / p['test_accounts'])}); "
            f"weights and thresholds from the earlier half only.", "",
            "| Method | Precision | Recall | F1 | Accounts escalated | Alerts not escalated |",
            "|---|---|---|---|---|---|"]
    for k, name in [("baseline_escalate_all", "Rule-based: escalate everything"),
                    ("no_graph_rules", f"Rules without the graph (≥{p['no_graph_rules_k']} rules)"),
                    ("graph_hand_weights", "BankWeave graph score, hand weights (no labels)"),
                    ("graph_calibrated", "BankWeave graph score, calibrated on dev split")]:
        x = r[k]
        out.append(f"| {name} | {pct(x['precision'])} | {pct(x['recall'])} | {x['f1']:.3f} | "
                   f"{x['escalated']:,} | {pct(x['alert_reduction'])} |")
    out += ["", src(e), ""]
if "E2_consortium_vs_single_bank" in R:
    e = R["E2_consortium_vs_single_bank"]
    b = e["results"]["best_single_bank"]
    out += ["### E2: no bank can see the ring alone", "",
            f"Across {e['results']['attempts']} laundering groups that span banks "
            f"(on average {e['results']['mean_banks_per_attempt']:.1f} banks each), the "
            f"best-placed single bank holds **{pct(b['mean_accounts_held'])}** of the ring's "
            f"accounts and holds a whole ring in **{pct(b['attempts_fully_held'])}** of cases. "
            f"It does observe {pct(b['mean_transfers_visible'])} of the laundering transfers, but "
            f"most counterparties are other banks' customers it can't investigate. The consortium "
            f"graph holds 100% of every ring.", "", src(e), ""]
if "E3_spnsa_hunt" in R:
    e = R["E3_spnsa_hunt"]
    r = e["results"]
    out += ["### E3: hunt mode (SPNSA reproduction, k=%d, r=%d)" % (e["params"]["k"], e["params"]["r"]), "",
            "| Seed feed | Subgraph accounts | Illicit ratio | Paper (HI-Small) |", "|---|---|---|---|",
            f"| Random (mean of {r['random']['runs']}) | {r['random']['nodes']:.0f} | {pct(r['random']['illicit_ratio'])} | {pct(r['paper_hi_small_k200_r1']['random'])} |",
            f"| Degree imbalance | {r['degree']['nodes']} | {pct(r['degree']['illicit_ratio'])} | {pct(r['paper_hi_small_k200_r1']['degree'])} |",
            f"| Motif-coherent (paper parameters) | {r['motif']['nodes']} | {pct(r['motif']['illicit_ratio'])} | {pct(r['paper_hi_small_k200_r1']['motif'])} |"]
    if "motif_no_degree_penalty" in r:
        out.append(f"| Motif, no degree penalty (post-hoc ablation) | {r['motif_no_degree_penalty']['nodes']} | {pct(r['motif_no_degree_penalty']['illicit_ratio'])} | — |")
    out += ["", f"Base rate in this graph: {pct(r['base_rate'])}. We did **not** reproduce the "
            f"paper's ranking: with its parameters the degree penalty inverts the motif score on our "
            f"20-bank slice (account-level AUC {r.get('account_auc', {}).get('motif_paper_params', '—')}, "
            f"vs {r.get('account_auc', {}).get('motif_no_degree_penalty', '—')} without the penalty), "
            "so degree imbalance wins here. All feeds beat random.",
            "", src(e), ""]
if "E4_passthrough" in R:
    e = R["E4_passthrough"]
    r = e["results"]
    out += ["### E4: pass-through matching", "",
            f"{r['flagged']} accounts flagged; {pct(r['precision'])} of them illicit vs a "
            f"{pct(r['base_rate'])} base rate. Chain-deduplicated value: {r['chain_deduplicated_value']:,.0f} "
            f"(IBM amounts are in many currencies, so this is a raw sum, not a USD figure).", "", src(e), ""]
if "E5_clue_expansion" in R:
    e = R["E5_clue_expansion"]
    t = e["results"]["per_round"]
    best = e["results"]["best_round"]
    out += ["### E5: clue-guided recovery", "",
            f"From 2 clue members of {e['params']['attempts']} laundering groups: best round {best} "
            f"reaches precision {pct(t[best]['precision'])}, recall {pct(t[best]['recall'])}. This is "
            "weak; the graph-signal version (no GNN) mostly finds the clue's immediate partners.",
            "", src(e), ""]
if "E6_trust_layer" in R:
    e = R["E6_trust_layer"]
    r = e["results"]
    out += ["### E6: trust layer on the agents' real cases", "",
            f"Over {r['cases']} cases the agents built from the live IBM slice:", "",
            f"- **Echo:** {pct(r['echo']['echo_rate'])} of {r['echo']['evidence_items']} evidence items repeated an origin already seen; "
            f"{r['echo']['claims_with_more_paths_than_sources']} of {r['echo']['claims']} claims had more supporting paths than independent sources. "
            f"Mean confidence {pct(r['echo']['mean_confidence_echo_proof'])} echo-proof vs {pct(r['echo']['mean_confidence_naive'])} counting paths.",
            f"- **Provenance gate:** {r['gate']['published']} of {r['gate']['sars']} SARs published, {r['gate']['divergent']} ended as divergence reports; "
            f"mean provenance fidelity {r['gate']['mean_pf']}; {r['gate']['needed_repair']} needed at least one repair round.",
            f"- **Cascading invalidation:** affected-node recall {pct(r['invalidation']['affected_recall'])} and precision "
            f"{pct(r['invalidation']['affected_precision'])} over {r['invalidation']['trials']} scripted dependency graphs.",
            f"- **Stale approvals:** {r['stale_actions_approved_without_override']} actions approved on overturned evidence without an override.",
            "", src(e), ""]
if "E7_performance" in R:
    e = R["E7_performance"]
    r = e["results"]
    out += ["### E7: speed (one local machine)", "",
            f"Consortium graph: {e['params']['accounts']:,} accounts, {e['params']['transfers']:,} transfers.", "",
            "| Operation | Median | 95th percentile |", "|---|---|---|"]
    for k, v in r.items():
        out.append(f"| {k.replace('_', ' ')} | {v.get('median_ms', v.get('ms'))} ms | "
                   f"{str(v['p95_ms']) + ' ms' if 'p95_ms' in v else ''} |")
    out += ["", src(e), ""]
out.append("<!-- results:end -->")

readme = ROOT / "README.md"
text = readme.read_text()
start, end = text.find("<!-- results:start"), text.find("<!-- results:end -->")
block = "\n".join(out)
if start >= 0 and end >= 0:
    text = text[:start] + block + text[end + len("<!-- results:end -->"):]
else:
    text = text.replace("_Results are filled in from `eval/results/*.json` (see the Scoreboard page)._",
                        block)
readme.write_text(text)
print(f"README results updated from {len(R)} result files")
